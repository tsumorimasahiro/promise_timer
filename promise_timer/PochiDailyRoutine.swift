import Foundation

/// Small gestures used by the scene; the routine chooses calm, related episodes.
enum PochiIdleMove: CaseIterable {
    case walk, sit, look, tilt, stretch, nap, hop, readRest
    case blink, ears, wag, approach, yawn
    case playInvite, bedtime, careRelax, cozyRest, welcome
    case shelfLook, deskWatch, ballPlay, specialRest
    case togetherRead, togetherTidy, togetherListen, togetherBreathe
    case pushups, squats, dumbbells, proudPose, proudWalk
}

/// Longer, quiet episodes while the person is doing their chosen activity.
/// No completion reactions or growth rewards are generated by these episodes.
enum PochiTogetherRoutine {
    static func moves(for activity: PochiRoomActivity, muscleLevel: Int = 0) -> [PochiIdleMove] {
        switch activity {
        case .strength:
            var result: [PochiIdleMove] = [.pushups, .sit, .squats, .cozyRest]
            if muscleLevel >= 1 { result += [.dumbbells, .sit] }
            if muscleLevel >= 2 { result += [.proudPose, .sit] }
            if muscleLevel >= 3 { result += [.proudWalk, .cozyRest] }
            return result
        case .read, .study: return [.togetherRead, .sit, .togetherRead, .stretch]
        case .clean: return [.togetherTidy, .sit, .togetherTidy, .wag]
        case .exercise, .stretch: return [.stretch, .walk, .sit, .stretch]
        case .stroll: return [.walk, .look, .walk, .sit]
        case .listen: return [.togetherListen, .cozyRest]
        case .breathe: return [.togetherBreathe, .sit]
        case .sleep, .rest: return [.nap, .cozyRest]
        case .eat, .drink: return [.sit, .cozyRest, .look]
        case .selfCare, .wash: return [.careRelax, .sit]
        case .idle, .joy, .pose: return [.sit, .look, .wag, .cozyRest]
        }
    }
}

struct PochiRoutineStep: Equatable {
    let move: PochiIdleMove
    let pause: TimeInterval
}

/// Session-only state, derived from local time and existing progress. No new save data.
/// Random selection is deliberately avoided: movement leads to rest, and night stays quiet.
struct PochiDailyRoutine {
    private var phase: PochiLifePhase?
    private var index = 0
    private var followUp: PochiRoomActivity?

    mutating func didComplete(_ activity: PochiRoomActivity) {
        followUp = activity.learningActivity
    }

    mutating func next(phase newPhase: PochiLifePhase, now: TimeInterval,
                       world: PochiWorldState, habits: PochiLifeHabits) -> PochiRoutineStep {
        if phase != newPhase {
            phase = newPhase
            index = 0
        }
        if newPhase == .deepNight {
            followUp = nil
            return .init(move: .nap, pause: 0)
        }
        if let completed = followUp {
            followUp = nil
            // Give the recorded action a quiet ending before continuing the daily routine.
            return .init(move: completed == .exercise || completed == .eat || completed == .drink
                ? .cozyRest : .sit, pause: 6)
        }
        let episode: [PochiIdleMove]
        switch newPhase {
        case .morning: episode = [.stretch, .look, .walk, .sit, .blink, .cozyRest, .ears, .sit]
        case .daytime: episode = [.look, .walk, .sit, .blink, .cozyRest, .ears, .walk, .sit, .nap]
        case .evening: episode = [.look, .sit, .yawn, .cozyRest, .blink, .bedtime]
        case .deepNight: episode = [.nap]
        }
        let move = episode[index % episode.count]
        index += 1
        if move == .cozyRest, world.totalCompletions >= PochiGrowthPolicy.special {
            return .init(move: .specialRest, pause: 8)
        }
        return .init(move: move, pause: move == .walk ? 12 : 6)
    }
}
