struct PochiPrimaryButton: View {
    let title: String
    var minHeight: CGFloat = 52
    var isEnabled = true
    let action: () -> Void

    var body: some View {
        Button(action: action) {
            Text(title)
                .font(pochiPixelFont(14))
                .lineLimit(1)
                .minimumScaleFactor(0.8)
                .frame(maxWidth: .infinity, minHeight: minHeight)
                .foregroundStyle(isEnabled ? Color.pochiOnAccent : Color.cocoa.opacity(0.55))
                .background(isEnabled ? Color.grassDark : Color.mist, in: RoundedRectangle(cornerRadius: 7))
                .contentShape(RoundedRectangle(cornerRadius: 7))
        }
        .buttonStyle(.plain)
        .disabled(!isEnabled)
    }
}

struct PochiOutlineButton: View {
    let title: String
    var minHeight: CGFloat = 52
    let action: () -> Void

    var body: some View {
        Button(action: action) {
            Text(title)
                .font(pochiPixelFont(14))
                .lineLimit(1)
                .minimumScaleFactor(0.8)
                .frame(maxWidth: .infinity, minHeight: minHeight)
                .foregroundStyle(Color.cocoa)
                .background(Color.pochiSurface, in: RoundedRectangle(cornerRadius: 7))
                .overlay(RoundedRectangle(cornerRadius: 7).stroke(Color.cocoa.opacity(0.3), lineWidth: 1.5))
        }
        .buttonStyle(.plain)
    }
}

struct PochiRetroFieldStyle: TextFieldStyle {
    func _body(configuration: TextField<Self._Label>) -> some View {
        configuration
            .foregroundStyle(Color.cocoa)
            .tint(Color.grassDark)
            .padding(.horizontal, 12)
            .frame(minHeight: 48)
            .background(Color.pochiSurface, in: RoundedRectangle(cornerRadius: 6))
            .overlay(RoundedRectangle(cornerRadius: 6).stroke(Color.cocoa.opacity(0.25), lineWidth: 1))
    }
}


/// Icon and explicit text share a single tap target; the icon is never the only clue.
struct PochiIconChoice: View {
    let kind: PochiPixelIconKind
    let title: String
    let isSelected: Bool
    var body: some View {
        HStack(spacing: 8) {
            PochiPixelGlyph(kind: kind, color: .grassDark, size: 32)
            Text(title).font(pochiPixelFont(12)).fixedSize(horizontal: false, vertical: true)
            Spacer(minLength: 0)
            if isSelected { PochiPixelGlyph(kind: .check, color: .grassDark, size: 16) }
        }
        .padding(10).frame(maxWidth: .infinity, minHeight: 64)
        .foregroundStyle(Color.cocoa)
        .background(isSelected ? Color.mist : Color.cream, in: RoundedRectangle(cornerRadius: 6))
        .overlay(RoundedRectangle(cornerRadius: 6).stroke(isSelected ? Color.grassDark : Color.cocoa.opacity(0.35), lineWidth: isSelected ? 2 : 1))
        .contentShape(RoundedRectangle(cornerRadius: 6))
    }
}

