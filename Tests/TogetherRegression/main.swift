import Foundation

func require(_ condition: @autoclosure () -> Bool, _ message: String) {
    if !condition() { fatalError(message) }
}
var calendar = Calendar(identifier: .gregorian)
calendar.timeZone = TimeZone(identifier: "Asia/Tokyo")!
let start = ISO8601DateFormatter().date(from: "2026-10-23T14:59:00Z")!
let preset = HabitPreset(id: "reading", title: "読書", iconName: "book", tintName: .lavender)
var session = PochiTogetherSession(preset: preset, now: start)
require(session.elapsed(at: start.addingTimeInterval(45)) == 45, "Elapsed time counts real seconds")
let restored = try JSONDecoder().decode(PochiTogetherSession.self, from: JSONEncoder().encode(session))
require(restored == session, "Active session and preset snapshot survive relaunch")
require(restored.elapsed(at: start.addingTimeInterval(7200)) == 7200, "Closed app and midnight do not lose time")
require(session.elapsed(at: start.addingTimeInterval(-100)) == 0, "Clock going backward never creates negative time")
session.pause(at: start.addingTimeInterval(40))
session.pause(at: start.addingTimeInterval(50))
require(session.elapsed(at: start.addingTimeInterval(500)) == 40, "Pause is idempotent and excludes break time")
var paused = try JSONDecoder().decode(PochiTogetherSession.self, from: JSONEncoder().encode(session))
require(paused.isPaused && paused.elapsed(at: start.addingTimeInterval(1000)) == 40, "Paused restoration stays paused")
paused.resume(at: start.addingTimeInterval(100))
paused.resume(at: start.addingTimeInterval(110))
let finish = start.addingTimeInterval(160)
require(paused.elapsed(at: finish) == 100, "Resume does not reset running time")
let first = paused.recording(in: [], at: finish, calendar: calendar)
require(first.count == 1 && first[0].durationSeconds == 100, "Timed completion saves duration")
require(calendar.component(.day, from: first[0].completedAt) == 24, "Cross-midnight sessions belong to completion day")
require(paused.recording(in: first, at: finish.addingTimeInterval(3), calendar: calendar) == first, "Interrupted save replay is idempotent")
let second = PochiTogetherSession(preset: preset, now: finish)
let merged = second.recording(in: first, at: finish.addingTimeInterval(90), calendar: calendar)
require(merged.count == 1 && merged[0].durationSeconds == 190, "Repeat sessions add duration without extra achievements")
require(merged[0].id == first[0].id && merged[0].completedAt == first[0].completedAt, "Daily record identity and date survive merging")
let plain = HabitLog(presetID: preset.id, title: preset.title, completedAt: finish)
let upgraded = second.recording(in: [plain], at: finish.addingTimeInterval(90), calendar: calendar)
require(upgraded.count == 1 && upgraded[0].durationSeconds == 90, "Existing one-tap achievement gains time")
let unrelated = HabitLog(presetID: "water", title: "水", completedAt: finish)
let previousDay = HabitLog(presetID: preset.id, title: "以前の名前", completedAt: start)
let distinct = second.recording(in: [previousDay, unrelated], at: finish.addingTimeInterval(90), calendar: calendar)
require(distinct.count == 3 && distinct[0] == previousDay && distinct[1] == unrelated, "Other dates and habits remain untouched")
let encoder = JSONEncoder(); encoder.dateEncodingStrategy = .iso8601
let decoder = JSONDecoder(); decoder.dateDecodingStrategy = .iso8601
let decoded = try decoder.decode([HabitLog].self, from: encoder.encode(merged))
require(decoded == merged, "Timed history uses existing ISO8601 format")
let legacy = try decoder.decode(HabitLog.self, from: Data(#"{"id":"old","presetID":"reading","title":"読書","completedAt":"2026-10-23T15:00:00Z"}"#.utf8))
require(legacy.durationSeconds == nil && legacy.timedSessionIDs.isEmpty, "Legacy untimed logs stay compatible")
require(PochiElapsedTime.string(65) == "01:05", "Minute display")
require(PochiElapsedTime.string(3661) == "1:01:01", "Hour display")
require(PochiElapsedTime.string(-10) == "00:00", "Negative values display safely")
for activity in PochiRoomActivity.allCases {
    require(!PochiTogetherRoutine.moves(for: activity).isEmpty, "Every activity has companion episodes")
}
require(PochiTogetherRoutine.moves(for: .read).contains(.togetherRead), "Reading companion")
require(PochiTogetherRoutine.moves(for: .clean).contains(.togetherTidy), "Tidying companion")
print("PASS: running/paused restoration, background elapsed time, midnight, clock rollback, repeat session aggregation, idempotency, legacy history, duration formatting, companion episodes")

let plank = HabitPreset(id: "strength.plank", title: "Plank", iconName: "plank", tintName: .peach,
                        workoutPlan: WorkoutPlan(mode: .timed, target: 10, sets: 2))
let startTime = Date(timeIntervalSince1970: 1000)
var timedSets = PochiTogetherSession(preset: plank, now: startTime)
precondition(timedSets.suggestedValues(at: startTime).isEmpty)
timedSets.pause(at: startTime.addingTimeInterval(4))
precondition(timedSets.remaining(at: startTime.addingTimeInterval(100)) == 6)
timedSets = try JSONDecoder().decode(PochiTogetherSession.self, from: JSONEncoder().encode(timedSets))
timedSets.resume(at: startTime.addingTimeInterval(100))
precondition(timedSets.elapsed(at: startTime.addingTimeInterval(200)) == 10)
timedSets.completeSet(at: startTime.addingTimeInterval(200))
precondition(timedSets.completedValues == [10] && timedSets.isPaused && timedSets.awaitingNextSet)
timedSets.resume(at: startTime.addingTimeInterval(201))
precondition(timedSets.isPaused)
timedSets.startNextSet(at: startTime.addingTimeInterval(300))
precondition(timedSets.remaining(at: startTime.addingTimeInterval(303)) == 7)
precondition(timedSets.suggestedValues(at: startTime.addingTimeInterval(303)) == [10, 3])
timedSets.completeSet(at: startTime.addingTimeInterval(400))
precondition(!timedSets.hasReachedSetLimit && timedSets.elapsed(at: startTime.addingTimeInterval(500)) == 20)
// A former two-set goal no longer stops a user who wants to continue.
timedSets.startNextSet(at: startTime.addingTimeInterval(500))
precondition(!timedSets.isPaused && timedSets.remaining(at: startTime.addingTimeInterval(503)) == 7)
timedSets.completeSet(at: startTime.addingTimeInterval(510))
precondition(timedSets.suggestedValues(at: startTime.addingTimeInterval(520)) == [10, 10, 10])
let actualLogs = timedSets.recording(in: [], at: startTime, calendar: .current, values: [10, 8])
precondition(actualLogs[0].workouts[0].values == [10, 8])
precondition(timedSets.recording(in: actualLogs, at: startTime, calendar: .current, values: [10, 8]) == actualLogs)
var repSession = PochiTogetherSession(preset: HabitPreset(title: "Crunch", iconName: "crunch", tintName: .peach))
precondition(repSession.suggestedValues(at: Date()) == [10])
repSession.completeSet(at: Date())
precondition(repSession.suggestedValues(at: Date()) == [10], "Rest must not propose an unstarted set")
repSession.startNextSet(at: Date())
precondition(repSession.suggestedValues(at: Date()) == [10, 10])
for _ in 1..<20 {
    repSession.completeSet(at: Date())
    repSession.startNextSet(at: Date())
}
precondition(repSession.hasReachedSetLimit && repSession.isPaused && repSession.completedValues.count == 20)
let restoredSets = try JSONDecoder().decode(PochiTogetherSession.self, from: JSONEncoder().encode(repSession))
precondition(restoredSets.suggestedValues(at: Date()) == Array(repeating: 10, count: 20))
print("PASS: countdown pause/relaunch/background cap, set boundaries, rest exclusion, partial sets, actual values and default reps")

let untimedNow = startTime.addingTimeInterval(30)
var untimed = PochiTogetherSession(preset: HabitPreset(title: "Pushups", iconName: "pushup", tintName: .peach), now: startTime)
untimed.pause(at: untimedNow)
let repOnly = untimed.recording(in: [], at: untimedNow, calendar: calendar, values: untimed.suggestedValues(at: untimedNow), recordsDuration: false)
precondition(repOnly[0].durationSeconds == nil && repOnly[0].workouts[0].values == [10])
let repeatedReps = PochiTogetherSession(preset: untimed.preset, now: untimedNow)
let combinedReps = repeatedReps.recording(in: repOnly, at: untimedNow, calendar: calendar, values: [10], recordsDuration: false)
precondition(combinedReps[0].durationSeconds == nil && combinedReps[0].workouts.count == 2)
precondition(untimed.recording(in: combinedReps, at: untimedNow, calendar: calendar, values: [10], recordsDuration: false) == combinedReps)
print("PASS: repetition workouts save reps without a duration, including repeated sessions and retry")
